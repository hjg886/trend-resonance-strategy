# ============== 工具函数 ==============

def parse_data(raw_text):
    """解析 'date close' 格式的数据"""
    lines = raw_text.strip().split('\n')
    data = []
    for line in lines:
        parts = line.strip().split()
        if len(parts) >= 2:
            date = parts[0]
            close = float(parts[1])
            data.append((date, close))
    return data

def calc_ma(data, period):
    """计算移动平均"""
    mas = [None] * len(data)
    for i in range(period - 1, len(data)):
        total = sum(data[j][1] for j in range(i - period + 1, i + 1))
        mas[i] = total / period
    return mas

def calc_daily_returns(closes):
    """计算日收益率"""
    returns = []
    for i in range(1, len(closes)):
        returns.append((closes[i] / closes[i-1]) - 1)
    return returns

def calc_vol20_annualized(closes):
    """计算20日年化波动率"""
    if len(closes) < 21:
        return None
    returns = calc_daily_returns(closes)
    last_20 = returns[-20:]
    mean_r = sum(last_20) / len(last_20)
    variance = sum((r - mean_r) ** 2 for r in last_20) / (len(last_20) - 1)
    daily_vol = math.sqrt(variance)
    annualized_vol = daily_vol * math.sqrt(252) * 100  # 转为百分比
    return annualized_vol

def calc_vol20_daily(closes):
    """计算20日波动率（非年化，百分比）"""
    if len(closes) < 21:
        return None
    returns = calc_daily_returns(closes)
    last_20 = returns[-20:]
    mean_r = sum(last_20) / len(last_20)
    variance = sum((r - mean_r) ** 2 for r in last_20) / (len(last_20) - 1)
    daily_vol = math.sqrt(variance) * 100
    return daily_vol

def calc_adx14(closes, highs_data=None, lows_data=None):
    """
    计算ADX(14) - Wilder's method
    使用收盘价近似high/low（因数据中只有收盘价）
    """
    n = len(closes)
    if n < 28:
        return None, None, None  # ADX, +DI, -DI
    
    # 如果没有high/low数据，用收盘价构造
    highs = closes[:] if highs_data is None else highs_data
    lows = closes[:] if lows_data is None else lows_data
    
    # 计算True Range (TR)
    tr_list = []
    plus_dm_list = []
    minus_dm_list = []
    
    for i in range(1, n):
        high = highs[i]
        low = lows[i]
        prev_close = closes[i-1]
        
        tr = max(
            high - low,
            abs(high - prev_close),
            abs(low - prev_close)
        )
        tr_list.append(tr)
        
        # +DM and -DM
        up_move = highs[i] - highs[i-1]
        down_move = lows[i-1] - lows[i]
        
        if up_move > down_move and up_move > 0:
            plus_dm_list.append(up_move)
        else:
            plus_dm_list.append(0)
        
        if down_move > up_move and down_move > 0:
            minus_dm_list.append(down_move)
        else:
            minus_dm_list.append(0)
    
    # Wilder smoothing for first 14 periods
    period = 14
    if len(tr_list) < period * 2:
        return None, None, None
    
    # Initial sum
    tr_smooth = sum(tr_list[:period])
    plus_dm_smooth = sum(plus_dm_list[:period])
    minus_dm_smooth = sum(minus_dm_list[:period])
    
    # Wilder smoothing for subsequent periods
    for i in range(period, len(tr_list)):
        tr_smooth = tr_smooth - (tr_smooth / period) + tr_list[i]
        plus_dm_smooth = plus_dm_smooth - (plus_dm_smooth / period) + plus_dm_list[i]
        minus_dm_smooth = minus_dm_smooth - (minus_dm_smooth / period) + minus_dm_list[i]
        
        # Calculate +DI and -DI
        if tr_smooth == 0:
            plus_di = 0
            minus_di = 0
        else:
            plus_di = (plus_dm_smooth / tr_smooth) * 100
            minus_di = (minus_dm_smooth / tr_smooth) * 100
        
        # Calculate DX
        if plus_di + minus_di == 0:
            dx = 0
        else:
            dx = abs(plus_di - minus_di) / (plus_di + minus_di) * 100
        
        # Store for ADX calculation
        if i == period:
            dx_list = [dx]
        else:
            dx_list.append(dx)
    
    # ADX = Wilder smoothing of DX over 14 periods
    if len(dx_list) < period:
        return None, None, None
    
    # First ADX = average of first 14 DX values
    adx = sum(dx_list[:period]) / period
    
    # Subsequent ADX values using Wilder smoothing
    for i in range(period, len(dx_list)):
        adx = (adx * (period - 1) + dx_list[i]) / period
    
    # Final +DI and -DI
    if tr_smooth == 0:
        final_plus_di = 0
        final_minus_di = 0
    else:
        final_plus_di = (plus_dm_smooth / tr_smooth) * 100
        final_minus_di = (minus_dm_smooth / tr_smooth) * 100
    
    return adx, final_plus_di, final_minus_di

def count_ma60_crossovers(closes, ma60):
    """统计近20个交易日收盘价与MA60的有效穿越次数"""
    crossings = 0
    # 从有MA60数据开始，取最近20个交易日
    valid_indices = [i for i in range(len(ma60)) if ma60[i] is not None]
    if len(valid_indices) < 2:
        return 0
    
    recent_indices = valid_indices[-20:] if len(valid_indices) >= 20 else valid_indices
    
    prev_above = None
    for i in recent_indices:
        above = closes[i] > ma60[i]
        if prev_above is not None and above != prev_above:
            crossings += 1
        prev_above = above
    
    return crossings

def check_ma60_strict(closes, ma60):
    """检查是否连续3日有效跌破MA60（严控定义）"""
    valid_indices = [i for i in range(len(ma60)) if ma60[i] is not None]
    if len(valid_indices) < 3:
        return False
    
    last3 = valid_indices[-3:]
    for i in last3:
        if closes[i] >= ma60[i]:
            return False
    return True

